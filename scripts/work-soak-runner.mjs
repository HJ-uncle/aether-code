export function parseOptions(args, env = process.env, cwd = process.cwd()) {
  const has = flag => args.includes(flag)
  const value = flag => { const index = args.indexOf(flag); return index < 0 ? undefined : args[index + 1] }
  const positive = (flag, fallback) => {
    if (!has(flag)) return fallback
    const n = Number(value(flag))
    if (!Number.isFinite(n) || n <= 0) throw new Error(`${flag} must be positive`)
    return n
  }
  const baseUrl = (value('--base-url') || env.AETHER_SOAK_BASE_URL || 'http://127.0.0.1:12323').replace(/\/+$/, '')
  const url = new URL(baseUrl)
  if (!['http:', 'https:'].includes(url.protocol) || url.username || url.password || url.search || url.hash) throw new Error('Engine URL must be HTTP(S), without credentials/query/fragment')
  const runId = value('--run-id') || `work-${new Date().toISOString().replace(/[-:.TZ]/g, '').slice(0, 14)}-${crypto.randomUUID().slice(0, 8)}`
  if (!/^[a-zA-Z0-9_-]{1,100}$/.test(runId)) throw new Error('Invalid run id')
  const durationHours = positive('--duration-hours', has('--smoke') ? 0.15 : 1)
  const thinking = value('--thinking') || 'off'
  if (!['off', 'auto'].includes(thinking)) throw new Error('thinking must be off or auto; effort tiers require a verified child contract')
  const minRounds = positive('--min-rounds', 2)
  const maxRounds = has('--max-rounds') ? positive('--max-rounds', 2) : has('--smoke') ? 2 : null
  if (maxRounds !== null && (!Number.isInteger(maxRounds) || maxRounds < minRounds)) throw new Error('max-rounds must be an integer >= min-rounds')
  const cronIntervalMinutes = positive('--cron-interval-minutes', 10)
  if (!Number.isInteger(cronIntervalMinutes) || cronIntervalMinutes < 10 || 60 % cronIntervalMinutes) throw new Error('Cron interval must divide 60 and be >= 10 minutes')
  const cronTimeoutSeconds = positive('--cron-timeout-seconds', 600)
  if (!Number.isInteger(cronTimeoutSeconds) || cronTimeoutSeconds > 86400) throw new Error('Cron timeout must be an integer from 1 to 86400 seconds')
  const minCronTriggers = positive('--min-cron-triggers', Math.max(1, Math.floor(durationHours * 60 / cronIntervalMinutes) - 1))
  if (!Number.isInteger(minRounds) || !Number.isInteger(minCronTriggers)) throw new Error('Minimum counts must be integers')
  const enginePid = has('--engine-pid') ? Number(value('--engine-pid')) : undefined
  const engineStartTicks = value('--engine-start-ticks')
  if ((has('--engine-pid') || has('--engine-start-ticks')) && (!Number.isSafeInteger(enginePid) || enginePid <= 0 || !/^\d{16,20}$/.test(engineStartTicks || ''))) throw new Error('Engine telemetry requires --engine-pid and verified --engine-start-ticks')
  return { baseUrl, runId, runRoot: path.resolve(value('--run-root') || path.join(cwd, '.ae', 'soak', runId)), durationHours,
    intervalMinutes: positive('--interval-minutes', has('--smoke') ? 0.5 : 5), requestTimeoutMs: positive('--request-timeout-ms', 600_000),
    alternateModel: value('--alternate-model'), thinking, minRounds, maxRounds, minCronTriggers, cronIntervalMinutes, cronTimeoutSeconds, enginePid, engineStartTicks, allowLocalModel: has('--allow-local-model'),
    continueOnTaskError: has('--continue-on-task-error'), execute: has('--execute') && !has('--discover') && !has('--dry-run') }
}

function atomicWrite(file, value) {
  const temp = `${file}.${process.pid}.${crypto.randomUUID()}.tmp`
  fs.writeFileSync(temp, `${JSON.stringify(value, null, 2)}\n`)
  fs.renameSync(temp, file)
}

export async function discover(client) {
  const [meta, models, agents, cron] = await Promise.all([
    client.request('/meta'), client.request('/api/v1/models'), client.request('/api/v1/agents'), client.request('/api/v1/cron')
  ])
  if (!Array.isArray(models) || !Array.isArray(agents) || !Array.isArray(cron)) throw new Error('Unexpected discovery API shape')
  return { discoveredAt: new Date().toISOString(), engine: { version: meta?.version, buildId: meta?.buildId, instanceId: meta?.instanceId },
    models: models.map(model => ({ modelId: model.modelId || model.model, provider: model.provider,
      baseUrl: endpointSummary(model.baseUrl), enabled: model.isEnabled !== false })), existingAgentCount: agents.length, existingCronCount: cron.length }
}

export function makePlan(config, discovery) {
  const enabled = discovery.models.filter(model => model.enabled)
  const qwen = enabled.find(model => model.modelId === 'qwen3.8-flash')
  const choices = enabled.filter(model => model.modelId !== 'qwen3.8-flash')
  const alternate = config.alternateModel ? choices.find(model => model.modelId === config.alternateModel) : choices.length === 1 ? choices[0] : null
  if (!qwen) throw new Error('Enabled qwen3.8-flash is required; no model configuration was fabricated')
  if (!alternate) throw new Error('Choose a distinct enabled model with --alternate-model')
  if (config.execute && !config.allowLocalModel && [qwen, alternate].some(model => !model.baseUrl || isLocalEndpoint(model.baseUrl))) {
    throw new Error('Selected provider endpoint is missing/local; refusing to count a fixture as a real model. --allow-local-model marks a local test only.')
  }
  const modelIds = [qwen.modelId, alternate.modelId]
  const sharedRoot = path.join(config.runRoot, 'shared-project')
  const sessions = ['shared', 'independent'].flatMap(kind => Array.from({ length: 5 }, (_, index) => ({
    kind, index, sessionId: `work-soak-${config.runId}-${kind}-${index + 1}`,
    workspace: kind === 'shared' ? sharedRoot : path.join(config.runRoot, `independent-${index + 1}`),
    initialModelIndex: (index + (kind === 'independent' ? 1 : 0)) % modelIds.length
  })))
  const cron = Array.from({ length: 5 }, (_, index) => ({ kind: 'cron', index,
    sessionId: `work-soak-${config.runId}-cron-${index + 1}`, name: `Aether soak ${config.runId} cron ${index + 1}`,
    workspace: path.join(config.runRoot, `cron-${index + 1}`), requestedModel: modelIds[index % 3 % modelIds.length], timeoutSeconds: config.cronTimeoutSeconds }))
  return { runId: config.runId, modelIds, sharedRoot, sessions, cron, limits: { minRounds: config.minRounds, minCronTriggers: config.minCronTriggers },
    thinking: config.thinking, cronThinking: config.thinking, cronTimeoutSeconds: config.cronTimeoutSeconds, continueOnTaskError: config.continueOnTaskError,
    coverage: 'Real engine HTTP/SSE engineering workload; UI requires separate Electron validation', providerMode: config.allowLocalModel ? 'local-override' : 'configured-remote' }
}

export async function cleanupOwned(client, manifest, emit, { drainTimeoutMs = 30_000 } = {}) {
  const errors = []
  const attempt = async (resource, id, action) => {
    try { await action(); return true } catch (error) {
      if (error.code === 40400) return true
      errors.push({ resource, id, error: error.message }); emit({ type: 'cleanup-error', resource, id, error: error.message }); return false
    }
  }
  for (const id of manifest.cronIds) {
    await attempt('cron-disable', id, () => client.request(`/api/v1/cron/${encodeURIComponent(id)}/disable`, { method: 'POST', body: {}, timeoutMs: 15_000 }))
    if (await attempt('cron-delete', id, () => client.request(`/api/v1/cron/${encodeURIComponent(id)}`, { method: 'DELETE', timeoutMs: 15_000 }))) emit({ type: 'cron-cleaned', id })
  }
  let drained = true
  for (const item of [...manifest.sessions, ...manifest.cron]) {
    await attempt('session-cancel', item.sessionId, () => client.request('/api/v1/chat/cancel', { method: 'POST', body: { sessionId: item.sessionId }, timeoutMs: 15_000 }))
    const deadline = Date.now() + drainTimeoutMs
    const ok = await attempt('session-drain', item.sessionId, async () => {
      for (;;) {
        const state = await client.request(`/api/v1/chat/status?sessionId=${encodeURIComponent(item.sessionId)}`, { timeoutMs: 15_000 })
        // A root can reach a terminal state while one of its native child
        // Agents is still running.  Deleting the owned Agent at that point
        // races the child and leaves an unfinished run in the evidence.  Read
        // and cancel children by their exact parent/session identity before
        // declaring the session drained.
        const children = await listSubagentRuns(client, item.sessionId, { timeoutMs: 15_000 })
        const activeChildren = children.filter(child => ['queued', 'running', 'waiting', 'cancelling'].includes(child.status))
        for (const child of activeChildren) {
          await client.request(`/api/v1/subagent/runs/${encodeURIComponent(child.runId)}/cancel`, { method: 'POST', body: {}, timeoutMs: 15_000 })
        }
        if (!state?.running && !['running', 'waiting'].includes(state?.run?.status) && activeChildren.length === 0) break
        if (Date.now() >= deadline) throw new Error('Session did not become terminal after cancellation')
        await delay(200)
      }
    })
    drained &&= ok
    if (ok) emit({ type: 'session-cancelled', sessionId: item.sessionId })
  }
  // Do not delete Agents that a durable producer could still be using.
  if (drained) for (const id of manifest.agentIds) {
    if (await attempt('agent-delete', id, () => client.request(`/api/v1/agents/${encodeURIComponent(id)}`, { method: 'DELETE', timeoutMs: 15_000 }))) emit({ type: 'agent-cleaned', id })
  }
  return errors
}

export function unverifiedCronRuns(runs, observation, final = false) {
  if (!Array.isArray(runs)) throw new Error('Cron runs response is malformed')
  const fresh = runs.filter(run => !observation.verifiedRunIds.includes(run.runId) && !observation.failedRunIds?.includes(run.runId))
  const failed = fresh.find(run => ['failed', 'cancelled', 'interrupted', 'waiting'].includes(run.status) || final && run.status === 'running')
  if (failed) throw new Error(`Cron ended ${failed.status} (${failed.runId})`)
  const finished = fresh.filter(run => run.status === 'succeeded')
  if (finished.length > 1) throw new Error('Cron has unverified intervening runs; latest snapshot cannot prove their tools')
  return finished
}

export async function monitorWork(work, observe, { signal, intervalMs = 15_000, abort } = {}) {
  let finished = false
  let outcome
  const pending = work().then(value => { outcome = { value } }, error => { outcome = { error } }).finally(() => { finished = true })
  try {
    while (!finished) {
      const wait = new AbortController()
      const linked = signal ? AbortSignal.any([signal, wait.signal]) : wait.signal
      try { await Promise.race([pending, delay(intervalMs, undefined, { signal: linked })]) } finally { wait.abort() }
      if (!finished) await observe()
    }
  } catch (error) {
    // A sibling failure aborts the polling delay; retain that original failure
    // rather than replacing the final run diagnosis with a generic AbortError.
    const cause = signal?.aborted && signal.reason instanceof Error ? signal.reason : error
    abort?.(cause)
    await pending
    throw cause
  }
  if (outcome?.error) throw outcome.error
  return outcome?.value
}

export async function settleStressBatch(items, worker, abort) {
  const outcomes = await Promise.allSettled(items.map(async item => {
    try { return await worker(item) } catch (error) { if (!error.taskFailure) abort(error); throw error }
  }))
  const fatal = outcomes.find(outcome => outcome.status === 'rejected' && !outcome.reason.taskFailure)
  if (fatal) throw fatal.reason
  return outcomes
}

export async function drainFailedSession(client, sessionId, expectedRunId, { signal, timeoutMs = 30_000 } = {}) {
  if (typeof expectedRunId !== 'string' || !expectedRunId.trim()) throw new Error('Failed-task cancellation requires the observed run identity')
  const deadline = Date.now() + timeoutMs
  const status = async () => {
    const state = await client.request(`/api/v1/chat/status?sessionId=${encodeURIComponent(sessionId)}`, { signal, timeoutMs: Math.min(10_000, timeoutMs) })
    if (!state.run || state.run.sessionId !== sessionId || state.run.runId !== expectedRunId) throw new Error('Failed-task cancellation encountered a different session or run identity')
    if (state.running && !state.run?.runId) throw new Error('Cannot cancel an active task without a durable run identity')
    return state
  }
  let state = await status()
  const runId = expectedRunId
  let rootCancelSent = false
  for (;;) {
    if (!rootCancelSent && (state.running || ['running', 'waiting'].includes(state.run?.status))) {
      await client.request('/api/v1/chat/cancel', { method: 'POST', body: { sessionId, runId }, signal, timeoutMs: Math.min(10_000, timeoutMs) })
      rootCancelSent = true
    }
    state = await status()
    const children = await listSubagentRuns(client, sessionId, { signal, timeoutMs: Math.min(10_000, timeoutMs) })
    const activeChildren = children.filter(child => ['queued', 'running', 'waiting', 'cancelling'].includes(child.status))
    for (const child of activeChildren) {
      await client.request(`/api/v1/subagent/runs/${encodeURIComponent(child.runId)}/cancel`, { method: 'POST', body: {}, signal, timeoutMs: Math.min(10_000, timeoutMs) })
    }
    if (!state.running && !['running', 'waiting'].includes(state.run?.status) && activeChildren.length === 0) break
    if (Date.now() >= deadline) throw new Error('Failed task did not become terminal after exact-run cancellation')
    await delay(Math.min(200, Math.max(1, deadline - Date.now())), undefined, { signal })
  }
  return { runId: state.run?.runId || runId || null, status: state.run?.status || 'absent' }
}

/** Read the durable native child archive without assuming one wire shape. */
export async function listSubagentRuns(client, sessionId, { signal, timeoutMs = 15_000 } = {}) {
  const payload = await client.request(`/api/v1/subagent/runs?parentSessionId=${encodeURIComponent(sessionId)}&view=legacy`, { signal, timeoutMs })
  const runs = Array.isArray(payload) ? payload : Array.isArray(payload?.runs) ? payload.runs : Array.isArray(payload?.data?.runs) ? payload.data.runs : []
  return runs.filter(run => run && run.parentSessionId === sessionId && typeof run.runId === 'string')
}

function mergeChildEvidence(streamChildren, durableChildren) {
  const merged = new Map((streamChildren ?? []).filter(child => child?.runId).map(child => [child.runId, child]))
  for (const durable of durableChildren) {
    const prior = merged.get(durable.runId)
    const summary = String(durable.resultSummary ?? durable.result?.summary ?? '')
    const resultNonces = [...new Set([...(prior?.resultNonces ?? []), ...(summary.match(/[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}/gi) ?? [])])].slice(0, 16)
    const readPaths = [...new Set([...(prior?.readPaths ?? []), ...(durable.toolCalls ?? []).filter(tool => tool.name === 'read_file' && tool.status === 'succeeded' && typeof tool.args?.path === 'string').map(tool => tool.args.path.slice(0, 1024))])].slice(0, 32)
    merged.set(durable.runId, { ...prior, ...durable, ...(resultNonces.length ? { resultNonces } : {}), ...(readPaths.length ? { readPaths } : {}) })
  }
  return [...merged.values()]
}

export async function execute(config, plan, discovery, client, { secrets = [] } = {}) {
  fs.mkdirSync(config.runRoot, { recursive: true })
  if (fs.existsSync(path.join(config.runRoot, 'manifest.json'))) throw new Error('Run manifest already exists; use a new root')
  const lockFile = path.join(config.runRoot, '.runner.lock')
  const lock = fs.openSync(lockFile, 'wx')
  fs.writeFileSync(lock, String(process.pid)); fs.closeSync(lock)
  const write = (name, value) => atomicWrite(path.join(config.runRoot, name), scrub(value, secrets))
  const emit = event => fs.appendFileSync(path.join(config.runRoot, 'events.jsonl'), `${JSON.stringify(scrub({ at: new Date().toISOString(), ...event }, secrets))}\n`)
  const started = Date.now()
  const deadline = started + config.durationHours * 3600_000
  const manifest = { ...plan, discovery, startedAt: new Date(started).toISOString(), deadline: new Date(deadline).toISOString(), durationHours: config.durationHours,
    intervalMinutes: config.intervalMinutes, cronIntervalMinutes: config.cronIntervalMinutes, pid: process.pid, round: 0, status: 'running', agentIds: [], cronIds: [], cronBindings: [],
    metrics: { turnsCompleted: 0, turnErrors: 0, turnsAborted: 0, streamBytes: 0, streamEvents: 0, verifiedCronTriggers: 0,
      permissionWaits: 0, permissionDenials: 0, permissionRecoveredTurns: 0, cronErrors: 0, integrationErrors: 0 },
    qualityFailures: [], sessionFeedback: {}, sessionEvidence: {}, cronEvidence: {} }
  const controller = new AbortController()
  const workloads = new Map()
  let stopReason = null
  let executionError = null
  let runningBatch = false
  let regularDone = false
  let engineMonitor = null
  const requestStop = reason => { stopReason ||= reason; controller.abort(new Error(reason)) }
  const onInt = () => requestStop('SIGINT')
  const onTerm = () => requestStop('SIGTERM')
  process.once('SIGINT', onInt); process.once('SIGTERM', onTerm)
  // A duration is a hard workload boundary, including slow/incomplete LLM
  // calls. Resource cleanup is recorded separately and may finish afterwards.
  const deadlineTimer = setTimeout(() => requestStop('deadline'), Math.max(1, deadline - Date.now()))
  const assertActive = () => controller.signal.throwIfAborted()
  const heartbeat = () => write('heartbeat.json', { runId: config.runId, pid: process.pid, status: manifest.status,
    at: new Date().toISOString(), round: manifest.round, metrics: manifest.metrics, runnerMemory: process.memoryUsage() })
  const save = () => { write('manifest.json', manifest); heartbeat() }
  const recordQualityFailure = failure => {
    if (manifest.qualityFailures.length >= 1000) throw new Error('Quality failure evidence limit exceeded')
    manifest.qualityFailures.push({ at: new Date().toISOString(), ...failure })
    save()
  }
  const timer = setInterval(() => {
    heartbeat()
    emit({ type: 'runner-sample', round: manifest.round, memory: process.memoryUsage(), cpuUsage: process.cpuUsage() })
  }, 10_000)
  timer.unref()
  const nextWorkload = (item, round) => {
    const workload = prepareWorkload(item, round, config.runId)
    workload.priorChild = (item.kind === 'cron' ? manifest.cronEvidence : manifest.sessionEvidence)[item.sessionId]?.lastChild || null
    workload.previousFailure = manifest.sessionFeedback[item.sessionId] || null
    workload.requestedModel = item.kind === 'cron' ? item.requestedModel : plan.modelIds[(item.initialModelIndex + round - 1) % plan.modelIds.length]
    workloads.set(item.sessionId, workload)
    return workload
  }
  const peerFor = item => item.kind === 'shared' ? `task-${(item.index + 1) % 5 + 1}-spec.json` : undefined
  const send = async (item, round) => {
    assertActive()
    const workload = workloads.get(item.sessionId)
    const requestedModel = plan.modelIds[(item.initialModelIndex + round - 1) % plan.modelIds.length]
    const startedAt = Date.now()
    let stream = null
    let phase = 'chat'
    try {
      stream = await chatWithDeniedPermissions(client, item.sessionId, workloadPrompt(item, workload, peerFor(item)), {
        model: requestedModel, subagentModel: requestedModel, ...(config.thinking === 'off' ? { thinkingMode: false } : {}),
        agentId: item.agentId, workspacePaths: [item.workspace], signal: controller.signal }, {
        timeoutMs: config.requestTimeoutMs, emit: event => {
          if (event.type === 'permission-waiting') manifest.metrics.permissionWaits += 1
          if (event.type === 'permission-denied') manifest.metrics.permissionDenials += 1
          if (event.type === 'permission-recovered') manifest.metrics.permissionRecoveredTurns += 1
          emit({ ...event, round, group: item.kind, index: item.index }); save()
        } })
      phase = 'configuration'
      const status = await client.request(`/api/v1/chat/status?sessionId=${encodeURIComponent(item.sessionId)}`, { signal: controller.signal, timeoutMs: 30_000 })
      if (status.run?.runId !== stream.runId) throw new Error('Root run identity changed before thinking configuration verification')
      if (config.thinking === 'off' && status.run?.requestConfig?.thinkingMode !== false) throw new Error('Parent run did not persist explicit thinkingMode:false')
      stream.thinkingMode = status.run?.requestConfig?.thinkingMode ?? null
      // SSE child snapshots are advisory and can arrive before the durable
      // archive commits the final result.  Reconcile them with the exact
      // parent-scoped archive before checking nonce/spec evidence, so a normal
      // commit race is recorded as a real child rather than a false failure.
      stream.children = mergeChildEvidence(stream.children, await listSubagentRuns(client, item.sessionId, { signal: controller.signal, timeoutMs: 30_000 }))
      phase = 'verification'
      const disk = await verifyWorkload(item, workload, stream, requestedModel, { signal: controller.signal, peer: peerFor(item) })
      manifest.metrics.turnsCompleted += 1; manifest.metrics.streamBytes += stream.bytes; manifest.metrics.streamEvents += stream.events
      const prior = manifest.sessionEvidence[item.sessionId] || { count: 0, actualModels: [] }
      manifest.sessionEvidence[item.sessionId] = { count: prior.count + 1, actualModels: [...new Set([...prior.actualModels, stream.actualModel])], lastRunId: stream.runId, lastRound: round, lastChild: disk.child }
      delete manifest.sessionFeedback[item.sessionId]
      emit({ type: 'turn-finished', group: item.kind, index: item.index, sessionId: item.sessionId, round, requestedModel, actualModel: stream.actualModel, thinking: config.thinking, durationMs: Date.now() - startedAt, stream, disk })
    } catch (error) {
      const aborted = controller.signal.aborted
      manifest.metrics[aborted ? 'turnsAborted' : 'turnErrors'] += 1
      stream ||= error.evidence || null
      emit({ type: aborted ? 'turn-aborted' : 'turn-error', sessionId: item.sessionId, round, requestedModel, actualModel: stream?.actualModel || null, stream, error: error.message })
      const taskFailure = error.taskFailure || phase === 'verification' && !/Harness fixture modified|Evidence file too large|Actual model mismatch|Missing successful root-run identity/.test(error.message)
      if (config.continueOnTaskError && !aborted && taskFailure) {
        try {
          const terminal = await drainFailedSession(client, item.sessionId, stream?.runId, { signal: controller.signal })
          manifest.sessionFeedback[item.sessionId] = error.message.slice(0, 1200)
          recordQualityFailure({ group: item.kind, sessionId: item.sessionId, runId: stream?.runId || null, round, error: error.message })
          emit({ type: 'task-error-drained', sessionId: item.sessionId, round, ...terminal })
          error.taskFailure = true
        } catch (drainError) { throw new Error(`Task failure could not be safely isolated: ${drainError.message}`, { cause: error }) }
      } else error.taskFailure = false
      throw error
    }
  }
  const pollCron = async (final = false) => {
    for (const item of manifest.cron.filter(job => job.jobId)) {
      assertActive()
      const { runs } = await client.request(`/api/v1/chat/runs?sessionId=${encodeURIComponent(item.sessionId)}`, { signal: controller.signal, timeoutMs: 30_000 })
      const observation = manifest.cronEvidence[item.sessionId] || { verifiedRunIds: [], failedRunIds: [], triggerCount: 0 }
      observation.failedRunIds ||= []
      const nextCronAttempt = async () => {
        nextWorkload(item, workloads.get(item.sessionId).round + 1)
        item.message = workloadPrompt(item, workloads.get(item.sessionId))
        const updated = await client.request(`/api/v1/cron/${encodeURIComponent(item.jobId)}`, { method: 'PUT', body: { message: item.message }, signal: controller.signal, timeoutMs: 30_000 })
        if (updated.timeoutSeconds !== config.cronTimeoutSeconds || config.thinking === 'off' && updated.thinkingMode !== false) throw new Error('Cron update lost its timeout/thinking configuration')
      }
      const recordCronFailure = async (run, error, stream) => {
        const terminal = await drainFailedSession(client, item.sessionId, run.runId, { signal: controller.signal })
        observation.failedRunIds.push(run.runId)
        manifest.cronEvidence[item.sessionId] = observation
        manifest.sessionFeedback[item.sessionId] = error.message.slice(0, 1200)
        manifest.metrics.cronErrors += 1
        recordQualityFailure({ group: 'cron', sessionId: item.sessionId, runId: run.runId, round: workloads.get(item.sessionId).round, error: error.message })
        emit({ type: 'cron-task-error', sessionId: item.sessionId, index: item.index, ...terminal, error: error.message, stream })
        await nextCronAttempt()
      }
      if (!Array.isArray(runs)) throw new Error('Cron runs response is malformed')
      for (const run of runs.filter(run => !observation.verifiedRunIds.includes(run.runId) && !observation.failedRunIds.includes(run.runId))) {
        if (run.sessionId !== item.sessionId || run.requestConfig?.cronJobId !== item.jobId || run.requestConfig?.cronTimeoutSeconds !== config.cronTimeoutSeconds) throw new Error('Cron run identity or timeout configuration does not match its job')
        if (config.continueOnTaskError && ['failed', 'cancelled', 'interrupted', 'waiting'].includes(run.status)) await recordCronFailure(run, new Error(`Cron ended ${run.status} (${run.runId}); unattended permission waits are not resumed`))
      }
      const finished = unverifiedCronRuns(runs, observation, final)
      if (!finished.length) continue
      const run = finished[0]
      const snapshot = await client.request(`/api/v1/chat/snapshot?sessionId=${encodeURIComponent(item.sessionId)}`, { signal: controller.signal, timeoutMs: 30_000 })
      if (snapshot?.run?.runId !== run.runId) throw new Error('Cron snapshot changed before evidence capture')
      if (config.thinking === 'off' && snapshot.run?.requestConfig?.thinkingMode !== false) throw new Error('Cron did not pass thinkingMode:false to its chat run')
      if (snapshot.run?.requestConfig?.cronTimeoutSeconds !== config.cronTimeoutSeconds || snapshot.run?.requestConfig?.cronJobId !== item.jobId) throw new Error('Cron run did not persist its originating job and explicit timeout budget')
      const collector = createCollector()
      for (const frame of snapshot.projection || []) collector.apply(frame)
      for (const child of snapshot.subagentRuns || []) if (child.parentConversationId === run.turnId || child.parentMessageId === run.assistantMessageId) collector.apply({ subagentEvent: { snapshot: child } })
      collector.apply({ run })
      const stream = { ...collector.result(), thinkingMode: snapshot.run?.requestConfig?.thinkingMode ?? null,
        cronTimeoutSeconds: snapshot.run?.requestConfig?.cronTimeoutSeconds, cronJobId: snapshot.run?.requestConfig?.cronJobId }
      stream.children = mergeChildEvidence(stream.children, await listSubagentRuns(client, item.sessionId, { signal: controller.signal, timeoutMs: 30_000 }))
      const workload = workloads.get(item.sessionId)
      let disk
      try { disk = await verifyWorkload(item, workload, stream, item.requestedModel, { signal: controller.signal }) }
      catch (error) {
        if (!config.continueOnTaskError || controller.signal.aborted || /Harness fixture modified|Evidence file too large|Actual model mismatch|Missing successful root-run identity/.test(error.message)) throw error
        await recordCronFailure(run, error, stream)
        continue
      }
      observation.verifiedRunIds.push(run.runId); observation.triggerCount += 1
      observation.lastTurnId = run.turnId; observation.actualModel = run.actualModelId; observation.lastFinishedAt = run.finishedAt
      observation.lastChild = disk.child
      observation.timeoutSeconds = snapshot.run.requestConfig.cronTimeoutSeconds
      manifest.cronEvidence[item.sessionId] = observation
      manifest.metrics.verifiedCronTriggers += 1
      delete manifest.sessionFeedback[item.sessionId]
      emit({ type: 'cron-trigger-verified', index: item.index, sessionId: item.sessionId, runId: run.runId, turnId: run.turnId, requestedModel: item.requestedModel, actualModel: stream.actualModel, stream, disk })
      // The next scheduler invocation must receive the newly persisted child
      // identity and nonce, otherwise a static Cron message repeats round one.
      await nextCronAttempt()
      save()
    }
  }
  const assertAcceptance = () => {
    if (manifest.qualityFailures.length) throw new Error(`${manifest.qualityFailures.length} task/Cron quality failures were recorded while the stress workload continued`)
    for (const item of manifest.sessions) {
      const evidence = manifest.sessionEvidence[item.sessionId]
      if (!evidence || evidence.count < config.minRounds || evidence.actualModels.length < 2) throw new Error(`Session ${item.sessionId} lacks required rounds and verified model switch`)
    }
    for (const item of manifest.cron) if ((manifest.cronEvidence[item.sessionId]?.triggerCount || 0) < config.minCronTriggers) throw new Error(`Cron ${item.index + 1} lacks required verified triggers`)
  }
  try {
    save(); emit({ type: 'run-started', runId: config.runId, coverage: plan.coverage, providerMode: plan.providerMode })
    if (config.enginePid) {
      engineMonitor = await startProcessMonitor({ pid: config.enginePid, creationTimeTicks: config.engineStartTicks, runRoot: config.runRoot,
        onError: error => { emit({ type: 'engine-monitor-error', error: error.message }); requestStop('engine-monitor-error') } })
      manifest.engineProcess = engineMonitor.summary
      save()
    }
    for (const item of [...manifest.sessions, ...manifest.cron]) nextWorkload(item, 1)
    for (let index = 0; index < 3; index += 1) {
      assertActive()
      // Store the id before honoring a signal; aborting a create POST may
      // orphan a resource that the server accepted before the disconnect.
      const agent = await client.request('/api/v1/agents', { method: 'POST', timeoutMs: 30_000, body: {
        name: `Aether soak ${config.runId} agent ${index + 1}`, model: plan.modelIds[index % plan.modelIds.length],
        description: `Temporary engineering collaborator owned by ${config.runId}`,
        systemPrompt: 'Implement scoped engineering tasks using the supplied tools: list_files, read_file, write_file, edit_file, execute_cmd, subagent. Every root turn must start with a fresh list_files call, including resumed turns: previous-turn tools do not count. Stay inside the workspace. Run exactly the two requested tests and one read-only subagent review (maxSteps=8). Specifications are complete: proceed without placeholder calls or unavailable ask_user/todo tools. Do not repeatedly reread or re-edit the same file. Never fabricate evidence or modify harness spec/verify files.',
        allowedTools: ['list_files', 'read_file', 'write_file', 'edit_file', 'execute_cmd', 'subagent']
      } })
      if (typeof agent?.id !== 'string' || !agent.id) throw new Error('Agent create response lacks id')
      manifest.agentIds.push(agent.id); emit({ type: 'agent-created', id: agent.id, model: plan.modelIds[index % plan.modelIds.length] }); save()
    }
    for (const [index, item] of manifest.sessions.entries()) item.agentId = manifest.agentIds[index % 3]
    for (const item of manifest.cron) {
      assertActive(); item.agentId = manifest.agentIds[item.index % 3]
      await client.request('/api/v1/workspace/bind', { method: 'POST', timeoutMs: 30_000, body: { sessionId: item.sessionId, workspaceRoot: item.workspace } })
      manifest.cronBindings.push({ sessionId: item.sessionId, workspace: item.workspace }); save(); assertActive()
      // Schedule after initialization, with two full minute ticks to spare.
      const startMinute = (new Date().getMinutes() + 2 + item.index) % 60
      const minutes = Array.from({ length: 60 / config.cronIntervalMinutes }, (_, n) => (startMinute + n * config.cronIntervalMinutes) % 60).sort((a, b) => a - b)
      item.cronExpr = `${minutes.join(',')} * * * *`
      item.message = workloadPrompt(item, workloads.get(item.sessionId)).replace(/工程第 1 轮/, '工程当前轮（以每次读取的 spec.round 为准）')
      const job = await client.request('/api/v1/cron', { method: 'POST', timeoutMs: 30_000, body: {
        name: item.name, description: `Owned by soak ${config.runId}`, cronExpr: item.cronExpr, sessionId: item.sessionId,
        agentId: item.agentId, message: item.message, enabled: true, timeoutSeconds: config.cronTimeoutSeconds, ...(config.thinking === 'off' ? { thinkingMode: false } : {})
      } })
      if (typeof job?.id !== 'string' || !job.id) throw new Error('Cron create response lacks id')
      item.jobId = job.id; manifest.cronIds.push(job.id); emit({ type: 'cron-created', id: job.id, index: item.index, cronExpr: item.cronExpr }); save()
      if (config.thinking === 'off' && job.thinkingMode !== false) throw new Error('Cron API did not persist explicit thinkingMode:false; update the engine before this soak')
      if (job.timeoutSeconds !== config.cronTimeoutSeconds) throw new Error('Cron API did not persist the explicit timeoutSeconds; update the engine before this soak')
    }
    let round = 0
    while (Date.now() < deadline) {
      assertActive()
      if ((config.maxRounds && round >= config.maxRounds) || (round >= config.minRounds && deadline - Date.now() < config.requestTimeoutMs)) {
        await pollCron()
        regularDone = true
      }
      if (!regularDone) {
        round += 1
        if (round > 1) for (const item of manifest.sessions) nextWorkload(item, round)
        runningBatch = true
        await monitorWork(
          () => (config.continueOnTaskError ? settleStressBatch : settledBatch)(manifest.sessions, item => send(item, round), error => controller.abort(error)),
          pollCron, { signal: controller.signal, abort: error => controller.abort(error) })
        const shared = manifest.sessions.filter(item => item.kind === 'shared')
        let integration
        try { integration = await verifySharedPipeline(shared, shared.map(item => workloads.get(item.sessionId)), { signal: controller.signal }) }
        catch (error) {
          if (!config.continueOnTaskError || controller.signal.aborted) throw error
          manifest.metrics.integrationErrors += 1
          recordQualityFailure({ group: 'shared-integration', round, error: error.message })
          integration = { failed: true, error: error.message }
          emit({ type: 'integration-error', round, error: error.message })
        }
        runningBatch = false
        manifest.round = round; emit({ type: 'round', round, integration }); save()
        await pollCron()
      }
      const nextRound = Math.min(deadline, Date.now() + config.intervalMinutes * 60_000)
      while (Date.now() < nextRound) {
        await delay(Math.min(15_000, nextRound - Date.now()), undefined, { signal: controller.signal })
        await pollCron(); heartbeat()
      }
    }
    stopReason ||= 'deadline'
    await pollCron(true)
    assertAcceptance()
  } catch (error) {
    // Reaching the deadline while idle is normal. An unfinished batch remains
    // red even if earlier rounds met the minimum: its work was not verified.
    let abortCause = error
    while (abortCause && abortCause !== controller.signal.reason) abortCause = abortCause.cause
    if (stopReason === 'deadline' && !runningBatch && controller.signal.aborted && abortCause === controller.signal.reason) {
      try {
        for (const item of manifest.cron.filter(job => job.jobId)) {
          const { runs } = await client.request(`/api/v1/chat/runs?sessionId=${encodeURIComponent(item.sessionId)}`, { timeoutMs: 10_000 })
          if (config.continueOnTaskError) {
            const observation = manifest.cronEvidence[item.sessionId] || { verifiedRunIds: [], failedRunIds: [], triggerCount: 0 }
            observation.failedRunIds ||= []
            for (const run of runs.filter(run => !observation.verifiedRunIds.includes(run.runId) && !observation.failedRunIds.includes(run.runId))) {
              if (run.sessionId !== item.sessionId || run.requestConfig?.cronJobId !== item.jobId) throw new Error('Cron final audit encountered a different session or job identity')
              observation.failedRunIds.push(run.runId)
              manifest.metrics.cronErrors += 1
              recordQualityFailure({ group: 'cron', sessionId: item.sessionId, runId: run.runId, error: `Cron ${run.status} without verified evidence at hard deadline` })
              emit({ type: 'cron-task-error', sessionId: item.sessionId, runId: run.runId, status: run.status, error: 'Unverified at hard deadline; cleanup will cancel any active work' })
            }
            manifest.cronEvidence[item.sessionId] = observation
          }
          const fresh = unverifiedCronRuns(runs, manifest.cronEvidence[item.sessionId] || { verifiedRunIds: [] }, true)
          if (fresh.length) throw new Error(`Cron ${item.index + 1} completed without verified evidence before deadline`)
        }
        assertAcceptance()
      } catch (failure) { executionError = failure }
    } else executionError = error
    stopReason ||= 'error'
    if (executionError) emit({ type: 'run-error', reason: stopReason, error: executionError.message })
  } finally {
    clearTimeout(deadlineTimer); clearInterval(timer); manifest.workloadFinishedAt = new Date().toISOString(); manifest.status = 'stopping'; manifest.stopReason = stopReason; save()
    try { manifest.cleanupErrors = await cleanupOwned(client, manifest, emit) } catch (error) { manifest.cleanupErrors = [{ resource: 'cleanup', error: error.message }] }
    if (engineMonitor) {
      try { await engineMonitor.stop() } catch (error) { executionError ||= error }
    }
    manifest.finishedAt = new Date().toISOString()
    manifest.durationCompleted = stopReason === 'deadline' && Date.now() >= deadline
    manifest.status = !executionError && !manifest.cleanupErrors.length && stopReason === 'deadline' ? 'completed' : stopReason === 'SIGINT' || stopReason === 'SIGTERM' ? 'stopped' : 'failed'
    if (executionError) manifest.failure = executionError.message
    manifest.acceptance = manifest.status === 'completed' ? plan.providerMode === 'local-override' ? 'local-test-only' : 'api-engineering-passed' : 'not-passed'
    emit({ type: 'run-stopped', status: manifest.status, acceptance: manifest.acceptance, reason: stopReason, metrics: manifest.metrics })
    save(); write('state.json', manifest)
    process.removeListener('SIGINT', onInt); process.removeListener('SIGTERM', onTerm)
    fs.unlinkSync(lockFile)
  }
  if (manifest.status !== 'completed') throw executionError || new Error(`Soak ${manifest.status}; see cleanup errors`)
  return manifest
}

export async function main(args = process.argv.slice(2), env = process.env) {
  if (args.includes('--help') || args.includes('-h')) { console.log(HELP); return }
  const config = parseOptions(args, env)
  const token = env.AETHER_SOAK_INSTANCE_TOKEN || (env.AETHER_SOAK_TOKEN_FILE ? fs.readFileSync(path.resolve(env.AETHER_SOAK_TOKEN_FILE), 'utf8').trim() : '')
  const secrets = [token, env.AETHER_SOAK_AUTH_TOKEN].filter(Boolean)
  const client = createClient({ ...config, token, authToken: env.AETHER_SOAK_AUTH_TOKEN, timeoutMs: config.requestTimeoutMs })
  const discovery = await discover(client)
  const plan = makePlan(config, discovery)
  fs.mkdirSync(config.runRoot, { recursive: true })
  if (fs.existsSync(path.join(config.runRoot, 'manifest.json'))) throw new Error('Refusing to overwrite an existing run')
  atomicWrite(path.join(config.runRoot, 'discovery.json'), scrub(discovery, secrets))
  atomicWrite(path.join(config.runRoot, 'plan.json'), scrub({ ...config, ...plan }, secrets))
  console.log(JSON.stringify({ runId: config.runId, runRoot: config.runRoot, modelIds: plan.modelIds, providerMode: plan.providerMode, mode: config.execute ? 'execute' : 'plan' }, null, 2))
  if (config.execute) return execute(config, plan, discovery, client, { secrets })
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main().catch(error => { console.error(`work-soak-runner failed: ${scrub(error.message, [process.env.AETHER_SOAK_INSTANCE_TOKEN, process.env.AETHER_SOAK_AUTH_TOKEN])}`); process.exitCode = 1 })
}
